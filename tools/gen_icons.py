#!/usr/bin/env python3
"""Generate src/ui/icons.h from the Codicons codicon.csv mapping.

Usage: python3 tools/gen_icons.py path/to/codicon.csv > src/ui/icons.h
"""
import csv, sys

rows = []
with open(sys.argv[1], newline="", encoding="utf-8-sig") as f:
    for r in csv.DictReader(f):
        rows.append((r["short_name"], int(r["unicode"], 16)))
rows.sort()

print("/* Generated by tools/gen_icons.py from @vscode/codicons - do not edit. */")
print("#pragma once\n")
print("#define ICON_MIN 0x%04X" % min(cp for _, cp in rows))
print("#define ICON_MAX 0x%04X\n" % max(cp for _, cp in rows))
seen = set()
for name, cp in rows:
    macro = "ICON_" + name.upper().replace("-", "_").replace("~", "_")
    if macro in seen:
        continue
    seen.add(macro)
    utf8 = "".join("\\x%02x" % b for b in chr(cp).encode("utf-8"))
    print('#define %-44s "%s" /* U+%04X */' % (macro, utf8, cp))
